/** Symbols with every word of the query in their name or group. */
export const searchSymbols = (query: string): CatalogueSymbol[] => {
  const words = query.toLowerCase().split(/\s+/).filter(Boolean);
  if (!words.length) return [];
  return SYMBOL_CATALOGUE.filter((s) => {
    const text = `${s.name} ${s.group}`.toLowerCase();
    return words.every((word) => text.includes(word));
  });
};

/** The 20-digit 2525D code ATAK writes: version 10, reality, then the choices around the entity. */
export const sidcOf = ({ symbol, affiliation, echelon, status, headquarters }: SymbolChoice) => {
  const unit = isLandUnit(symbol);
  const code = [
    "100",
    AFFILIATIONS[affiliation].d,
    symbol.id.slice(0, 2),
    "0",
    unit && headquarters ? "2" : "0",
    unit ? ECHELONS[echelon].d : "00",
    symbol.id.slice(2),
    "0000",
  ].join("");
  return withUnitStatus(code, status);
};

