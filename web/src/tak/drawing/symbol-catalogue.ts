export const SYMBOL_CATALOGUE: CatalogueSymbol[] = ROWS.map(([id, cot, name]) => ({
  id,
  cot,
  name,
  group: GROUP[id.slice(0, 2)] ?? "Other",
}));

const byId = new Map(SYMBOL_CATALOGUE.map((s) => [s.id, s]));

const catalogued = (id: string): CatalogueSymbol => {
  const symbol = byId.get(id);
  if (!symbol) throw new Error(`No 2525D symbol ${id} in the catalogue`);
  return symbol;
};

