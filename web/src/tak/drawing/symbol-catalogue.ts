/**
 * MIL-STD-2525D point symbols to place as markers, written the way ATAK's 2525
 * point dropper writes them: the numeric code in `__milsym`/`__milicon` and a
 * CoT type from the matching 2525C function code (CotUtils.cotTypeFromMil2525C),
 * e.g. friendly infantry 10031000001211000000 as a-f-G-U-C-I.
 *
 * The rows were generated once from the C5ISR renderer's 2525D names and its
 * 2525C→D table: land units, equipment and installations, military aircraft
 * and control points milsymbol can draw.
 */

export type Affiliation = "f" | "h" | "n" | "u";

/** The 4th digit of a 2525D code. */
export const AFFILIATIONS: Record<Affiliation, { label: string; d: string }> = {
  f: { label: "Friend", d: "3" },
  h: { label: "Hostile", d: "6" },
  n: { label: "Neutral", d: "4" },
  u: { label: "Unknown", d: "1" },
};

/** Land unit echelons, the 9th–10th digits of a 2525D code. */
export const ECHELONS = {
  none: { label: "None", d: "00" },
  team: { label: "Team/crew", d: "11" },
  squad: { label: "Squad", d: "12" },
  section: { label: "Section", d: "13" },
  platoon: { label: "Platoon", d: "14" },
  company: { label: "Company", d: "15" },
  battalion: { label: "Battalion", d: "16" },
} as const;

export type Echelon = keyof typeof ECHELONS;

export const SYMBOL_STATUSES: UnitStatus[] = ["present", "anticipated", "damaged", "destroyed"];

export type CatalogueSymbol = {
  /** 2525D symbol set and entity code, e.g. 10121100 for infantry. */
  id: string;
  /** What ATAK's CoT type has after `a-<affiliation>-`, e.g. G-U-C-I. */
  cot: string;
  name: string;
  group: string;
};

export type SymbolChoice = {
  symbol: CatalogueSymbol;
  affiliation: Affiliation;
  echelon: Echelon;
  status: UnitStatus;
  headquarters: boolean;
};

